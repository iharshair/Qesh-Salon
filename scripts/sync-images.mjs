// Scans public/images and writes src/data/images.js (slot id -> path | null) and IMAGE_SLOTS.md.
// Run automatically before dev/build. Drop a correctly named file into public/images and run `npm run sync-images`.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SLOTS, SLOT_IDS } from '../src/data/slots.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'public/images');
const EXT = /\.(jpg|jpeg|png|webp)$/i;
const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => EXT.test(f)) : [];
const byId = new Map();
const unplaced = [];
for (const f of files) {
  const id = f.replace(EXT, '').toLowerCase();
  if (SLOT_IDS.has(id)) byId.set(id, '/images/' + f);
  else unplaced.push(f);
}
const manifest = {};
for (const s of SLOTS) manifest[s.id] = byId.get(s.id) || null;

fs.writeFileSync(
  path.join(root, 'src/data/images.js'),
  `// GENERATED by scripts/sync-images.mjs — do not edit by hand.\n// slot id -> file path (or null = blank slot). Add a file to public/images with the exact slot name, then run \`npm run sync-images\`.\nexport const IMAGES = ${JSON.stringify(manifest, null, 2)};\n`
);

// IMAGE_SLOTS.md
let md = '# IMAGE SLOTS\n\nFile name (without extension) = slot id. Accepted: .jpg .jpeg .png .webp. Put files in `public/images/`.\n';
const filled = SLOTS.filter((s) => manifest[s.id]).length;
md += `\n**Filled: ${filled} / ${SLOTS.length}**\n`;
const groups = [...new Set(SLOTS.map((s) => s.group))];
for (const g of groups) {
  md += `\n## ${g}\n\n| Slot id | Where it appears | Recommended size | Status |\n|---|---|---|---|\n`;
  for (const s of SLOTS.filter((x) => x.group === g))
    md += `| \`${s.id}\` | ${s.where} | ${s.size} | ${manifest[s.id] ? 'FILLED' : 'blank'} |\n`;
}
md += '\n## Unplaced images\n\nFiles whose names match no slot. They are not used on the site.\n\n';
const extra = [
  ['logo_upscaled_8k_transparent.png', 'Client logo (source). Used to make `logo_dark.png` (cropped to the artwork and resized). `logo_light` is the same file with a CSS filter. Please send `logo_light.png` if you want a custom light version.'],
];
for (const f of unplaced) md += `- \`${f}\` — suggested slot: (rename to a slot id above)\n`;
for (const [f, note] of extra) md += `- \`${f}\` — ${note}\n`;
if (!unplaced.length && !extra.length) md += '_None._\n';
fs.writeFileSync(path.join(root, 'IMAGE_SLOTS.md'), md);
console.log(`images: ${filled}/${SLOTS.length} slots filled, ${unplaced.length} unplaced file(s)`);
